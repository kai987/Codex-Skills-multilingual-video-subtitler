test("single-format failure, cancellation, concurrent writer and path/symlink escape", async () => {
  const f = await prepared(),
    out = path.join(f.original, "new"),
    controller = new AbortController();
  controller.abort();
  await assert.rejects(
    reportRevision(f.manifest, { outputRoot: out, signal: controller.signal }),
  );
  await assert.rejects(
    reportRevision(f.manifest, {
      outputRoot: out,
      exportPartial: true,
      writeFile: async (p, ...args) => {
        if (p.endsWith(".ass")) throw Error("ONE_FORMAT_FAILURE");
        return fs.writeFile(p, ...args);
      },
    }),
    /ONE_FORMAT_FAILURE/,
  );
  assert.equal(
    (await fs.readdir(out)).filter((n) => n.startsWith("report-")).length,
    0,
  );
  const both = await Promise.allSettled([
    reportRevision(f.manifest, { outputRoot: out }),
    reportRevision(f.manifest, { outputRoot: out }),
  ]);
  assert.equal(both.filter((x) => x.status === "fulfilled").length, 1);
  assert.ok(
    String(both.find((x) => x.status === "rejected").reason).includes("EEXIST"),
  );
  await fs.symlink(f.root, path.join(f.original, "link"));
  await assert.rejects(
    reportRevision(f.manifest, {
      outputRoot: path.join(f.original, "link", "child"),
    }),
  );
  await assert.rejects(
    reportRevision(f.manifest, { outputRoot: out + "/../escape" }),
    /PATH_TRAVERSAL/,
  );
});
test("relocated minimal evidence works with process APIs forbidden and old source read-only", async () => {
  const f = await prepared(),
    first = await reportRevision(f.manifest, {
      outputRoot: path.join(f.original, "one"),
    }),
    manifest = JSON.parse(
      await fs.readFile(
        path.join(first.revision, "report-manifest.json"),
        "utf8",
      ),
    ),
    copy = path.join(f.original, "minimal");
  for (const entry of manifest.input.evidence) {
    const to = path.join(copy, entry.path);
    await fs.mkdir(path.dirname(to), { recursive: true });
    await fs.copyFile(path.join(f.root, entry.path), to);
    await fs.chmod(to, 0o444);
  }
  const saved = Object.fromEntries(
    [
      "spawn",
      "spawnSync",
      "exec",
      "execSync",
      "execFile",
      "execFileSync",
      "fork",
    ].map((k) => [k, cp[k]]),
  );
  let attempts = 0;
  try {
    for (const k of Object.keys(saved))
      cp[k] = () => {
        attempts++;
        throw Error("OFFLINE_PROCESS_FORBIDDEN");
      };
    syncBuiltinESMExports();
    const result = await reportRevision(path.join(copy, "experiment.json"), {
      outputRoot: path.join(f.original, "two"),
      exportPartial: true,
    });
    assert.equal(result.B.partial, "generated");
    assert.equal(attempts, 0);
    assert.ok(Object.values(result.operations).every((n) => n === 0));
    await verifyRevision(
      result.revision,
      path.basename(result.revision).slice(7),
    );
  } finally {
    for (const [k, v] of Object.entries(saved)) cp[k] = v;
    syncBuiltinESMExports();
  }
});
