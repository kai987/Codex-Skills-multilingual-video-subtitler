function record(
  start = "00:00:00,000",
  end = "00:00:01,000",
  text = "neutral",
  chunk = c,
  manifest = m,
) {
  return mapRaw(
    `1\n${start} --> ${end}\n${text}\n`,
    "a".repeat(64),
    chunk,
    manifest.pcm.sampleRate,
    manifest.audioOffset,
    manifest.sourceEnd,
  )[0];
}
