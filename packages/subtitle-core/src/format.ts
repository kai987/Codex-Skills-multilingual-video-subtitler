import type { SubtitleCue } from "@mvl/shared";

import { formatAssClock, formatSrtClock, formatVttClock } from "./time.js";

export interface AssStyleConfiguration {
  fontName: string;
  fontSize: number;
  dialogueAlignment: number;
  thoughtAlignment: number;
  musicAlignment: number;
  musicItalic: boolean;
  marginVertical: number;
}

export const DEFAULT_ASS_STYLE_CONFIGURATION: Readonly<AssStyleConfiguration> =
  {
    fontName: "sans-serif",
    fontSize: 66,
    dialogueAlignment: 2,
    thoughtAlignment: 9,
    musicAlignment: 8,
    musicItalic: true,
    marginVertical: 40,
  };

export function formatSrt(cues: readonly SubtitleCue[]): string {
  return `${cues
    .map(
      (cue, index) =>
        `${index + 1}\n${formatSrtClock(cue.start)} --> ${formatSrtClock(cue.end)}\n${cue.style === "thought" || cue.style === "music" ? `<i>${cue.text}</i>` : cue.text}`,
    )
    .join("\n\n")}\n`;
}

export function formatVtt(cues: readonly SubtitleCue[]): string {
  const body = cues
    .map(
      (cue) =>
        `${cue.id}\n${formatVttClock(cue.start)} --> ${formatVttClock(cue.end)}${cue.style === "thought" ? " line:0 align:end" : cue.style === "music" ? " line:0 align:center" : ""}\n${cue.style === "thought" || cue.style === "music" ? `<i>${cue.text}</i>` : cue.text}`,
    )
    .join("\n\n");
  return `WEBVTT\n\n${body}\n`;
}

function escapeAssText(text: string): string {
  return text
    .replaceAll("\\", "\\\\")
    .replaceAll("{", "\\{")
    .replaceAll("}", "\\}")
    .replaceAll("\n", "\\N");
}

export function formatAss(
  cues: readonly SubtitleCue[],
  configuration: Partial<AssStyleConfiguration> = {},
): string {
  const styles: AssStyleConfiguration = {
    ...DEFAULT_ASS_STYLE_CONFIGURATION,
    ...configuration,
  };
  const musicItalic = styles.musicItalic ? -1 : 0;
  const header = `[Script Info]
; Generated by multilingual-video-subtitler
ScriptType: v4.00+
WrapStyle: 0
ScaledBorderAndShadow: yes
YCbCr Matrix: None
Collisions: Normal
PlayResX: 1920
PlayResY: 1080

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: Default,${styles.fontName},${styles.fontSize},&H00FFFFFF,&H000000FF,&H00101010,&H80000000,0,0,0,0,100,100,0,0,1,2,1,${styles.dialogueAlignment},60,60,${styles.marginVertical},1
Style: Thought,${styles.fontName},${styles.fontSize},&H00FFFFFF,&H000000FF,&H00101010,&H80000000,0,-1,0,0,100,100,0,0,1,2,1,${styles.thoughtAlignment},60,60,${styles.marginVertical},1
Style: Music,${styles.fontName},${styles.fontSize},&H00FFFFFF,&H000000FF,&H00101010,&H80000000,0,${musicItalic},0,0,100,100,0,0,1,2,1,${styles.musicAlignment},60,60,${styles.marginVertical},1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text`;
  const dialogue = cues.map((cue) => {
    const speaker = (cue.speaker ?? "").replaceAll(",", " ");
    const style =
      cue.style === "thought"
        ? "Thought"
        : cue.style === "music"
          ? "Music"
          : "Default";
    return `Dialogue: 0,${formatAssClock(cue.start)},${formatAssClock(cue.end)},${style},${speaker},0,0,0,,${escapeAssText(cue.text)}`;
  });
  return `${header}\n${dialogue.join("\n")}\n`;
}
